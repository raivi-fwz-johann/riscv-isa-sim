auto gost_gf256_mul = [](uint8_t x, uint8_t y) {
  uint8_t z = 0;
  while (y) {
    if (y & 1)
      z ^= x;
    x = (x << 1) ^ (x & 0x80 ? 0xC3 : 0x00);
    y >>= 1;
  }
  return z;
};

auto xvkgost_kuznz_xor = [&](const EGU8x16_t &state, const EGU8x16_t &round_key) {
  EGU8x16_t new_state;
  for (unsigned elt = 0; elt < state.size(); ++elt) {
    new_state[elt] = state[elt] ^ round_key[elt];
  } 
  return new_state;
};

auto xvkgost_kuzn = [&](const uint8_t R16_mat[16][16], const EGU8x16_t &state) {
  EGU8x16_t new_state;
  for (unsigned i = 0; i < 16; ++i) {
    new_state[i] = 0;
    for (unsigned j = 0; j < 16; ++j) {
      new_state[i] ^= gost_gf256_mul(R16_mat[i][j], state[j]);
    }
  }
  return new_state;
};

